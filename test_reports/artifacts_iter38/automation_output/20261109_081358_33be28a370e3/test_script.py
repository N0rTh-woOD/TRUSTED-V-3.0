async def run_test(page, output_dir, page_url):
    await page.set_viewport_size({'width':1920,'height':1080})
    try:
        await page.get_by_test_id('email-input').fill('demo@trusted-v.com')
        await page.get_by_test_id('password-input').fill('TEST_invalid_password')
        async with page.expect_response(lambda r:'/api/auth/login' in r.url) as info:
            await page.get_by_test_id('login-btn').click()
        response=await info.value
        body=await response.json()
        print('Rejected-login status/detail:',response.status,body)
        assert response.status == 401
        await page.get_by_text(body['detail'],exact=True).wait_for()
        assert await page.get_by_test_id('login-btn').is_enabled()
        print('PASS error displayed with server detail; retry enabled (previous assertion expected wrong copy)')
        await page.get_by_test_id('password-input').fill('demo@2025')
        await page.get_by_test_id('password-input').press('Enter')
        await page.get_by_test_id('homepage').wait_for(timeout=20000)
        print('PASS demo keyboard login/retry')
        await page.reload()
        await page.get_by_test_id('homepage').wait_for(timeout=20000)
        assert await page.evaluate('Boolean(localStorage.getItem("token"))')
        await page.get_by_test_id('nav-account-menu').click()
        assert await page.get_by_test_id('nav-account-dropdown').get_by_text('demo@trusted-v.com',exact=True).is_visible()
        assert await page.get_by_test_id('nav-admin').count() == 0
        print('PASS refreshed demo session and normal-user role')
        await page.get_by_test_id('nav-logout').click()
        await page.get_by_test_id('login-page').wait_for()
        assert await page.evaluate('localStorage.getItem("token") === null')
        print('PASS demo logout')
        await page.get_by_test_id('email-input').fill('admin@trusted-v.com')
        await page.get_by_test_id('password-input').fill('bosch@2425')
        await page.get_by_test_id('login-btn').click()
        await page.get_by_test_id('homepage').wait_for(timeout=20000)
        await page.reload()
        await page.get_by_test_id('homepage').wait_for(timeout=20000)
        await page.get_by_test_id('nav-account-menu').click()
        assert await page.get_by_test_id('nav-account-dropdown').get_by_text('admin@trusted-v.com',exact=True).is_visible()
        assert await page.get_by_test_id('nav-admin').is_visible()
        print('PASS admin login/refresh/role preserved')
        await page.get_by_test_id('nav-logout').click()
        await page.get_by_test_id('login-page').wait_for()
        assert await page.evaluate('localStorage.getItem("token") === null')
        print('PASS admin logout')
        error_text = await page.evaluate('''() => { const errorElements = Array.from(document.querySelectorAll('.error, [class*="error"], [id*="error"]')); return errorElements.map(el => el.textContent).join(', '); }''')
        print(f'Found error message: {error_text}' if error_text else 'No error messages found on the page')
    except Exception as e:
        print(f'FAIL: {type(e).__name__}: {e}')
